import AppKit
import ApplicationServices
import ImageIO
import UniformTypeIdentifiers

/// Read material supplied by the copying app. Avoid file URLs and representations
/// marked private, transient or remote, including markers on a second item.
enum ClipboardPasteboard {
    private static let restored = NSPasteboard.PasteboardType("org.nspasteboard.RestoredType")
    private static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        restored, .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"), .init("com.typeit4me.clipping"),
        .init("Pasteboard generator type"), .init("com.apple.is-remote-clipboard")
    ]
    private static let privateApps = [
        "com.apple.Passwords", "com.apple.keychainaccess", "com.1password.1password",
        "com.agilebits.onepassword", "com.bitwarden.desktop", "com.bitwarden.desktop.mas",
        "com.dashlane.dashlanephonefinal", "org.keepassxc.keepassxc", "in.sinew.enpass-desktop"
    ].map { $0.lowercased() }

    static func ignores(_ bundleID: String?) -> Bool {
        guard let id = bundleID?.lowercased() else { return false }
        if id.hasPrefix("com.agilebits.onepassword") { return true }
        return privateApps.contains { id == $0 || id.hasPrefix($0 + ".") }
    }

    static func read(_ board: NSPasteboard, expectedChange: Int, frontmostBundleID: String?) -> [ClipboardContent] {
        guard board.changeCount == expectedChange, !ignores(frontmostBundleID),
              let types = board.types, ignoredTypes.isDisjoint(with: types),
              let items = board.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ ignoredTypes.isDisjoint(with: $0.types) }) else { return [] }
        for item in items where item.types.contains(source) {
            if ignores(item.string(forType: source)) { return [] }
        }
        var result: [ClipboardContent] = []
        var bytes = 0
        for item in items.prefix(200) {
            guard board.changeCount == expectedChange else { return [] }
            guard !item.types.contains(.fileURL), let content = content(of: item) else { continue }
            switch content {
            case .text(let text): bytes += text.utf8.count
            case .image(let data): bytes += data.count
            }
            if bytes > 100 * 1024 * 1024 { break }
            result.append(content)
        }
        return board.changeCount == expectedChange ? result : []
    }

    private static func content(of item: NSPasteboardItem) -> ClipboardContent? {
        // Prefer a bitmap to its alt text when an app supplies both for a copied image.
        let imageTypes = [.png, .tiff] + item.types.filter {
            $0 != .png && $0 != .tiff && UTType($0.rawValue)?.conforms(to: .image) == true
        }
        for type in imageTypes where item.types.contains(type) {
            if let data = item.data(forType: type), let image = normalizedImage(data) { return .image(image) }
        }
        let text = item.string(forType: .string) ?? item.string(forType: .URL)
        guard let text, !text.isEmpty, text.utf8.count <= ClipboardStore.maximumItemBytes else { return nil }
        return .text(text)
    }

    private static func normalizedImage(_ data: Data) -> Data? {
        guard data.count <= 128 * 1024 * 1024,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [String: Any],
              let width = properties[kCGImagePropertyPixelWidth as String] as? Int,
              let height = properties[kCGImagePropertyPixelHeight as String] as? Int,
              width > 0, height > 0, width <= 48_000_000 / height else { return nil }
        if CGImageSourceGetType(source) as String? == UTType.png.identifier {
            return data.count <= ClipboardStore.maximumItemBytes ? data : nil
        }
        let png = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(png, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImageFromSource(dest, source, 0, nil)
        guard CGImageDestinationFinalize(dest), png.length <= ClipboardStore.maximumItemBytes else { return nil }
        return png as Data
    }

    static func write(_ content: ClipboardContent, to board: NSPasteboard) -> Bool {
        let item = NSPasteboardItem()
        switch content {
        case .text(let text):
            guard item.setString(text, forType: .string) else { return false }
        case .image(let png):
            guard item.setData(png, forType: .png) else { return false }
        }
        // Observers in both Shad editions can recognize a restoration.
        item.setData(Data(), forType: restored)
        item.setString("", forType: source)
        board.clearContents()
        return board.writeObjects([item])
    }
}

@MainActor final class ClipboardTool: ObservableObject {
    @Published private(set) var entries: [ClipboardEntry] = []
    @Published private(set) var paused = false
    @Published private(set) var issue: String?
    private let store: ClipboardStore
    private let pasteboard: NSPasteboard
    private let worker = DispatchQueue(label: "io.github.syedshad.shadtools.clipboard", qos: .userInitiated)
    private let instance = UUID().uuidString
    private static let changes = Notification.Name("io.github.syedshad.shadtools.clipboard.changed")
    private var observer: NSObjectProtocol?
    private var monitor: Task<Void, Never>?
    private var revision = 0
    private var emptyRetries = 0
    private static let bootSession: String = {
        var value = [CChar](repeating: 0, count: 64)
        var size = value.count
        if sysctlbyname("kern.bootsessionuuid", &value, &size, nil, 0) == 0 { return String(cString: value) }
        var boot = timeval()
        size = MemoryLayout.size(ofValue: boot)
        _ = sysctlbyname("kern.boottime", &boot, &size, nil, 0)
        return String(boot.tv_sec)
    }()
    private var lastChange: Int
    private var pasteTarget: NSRunningApplication?
    private lazy var window = ClipboardHistoryWindow(tool: self)

    convenience init() { self.init(store: ClipboardStore(), pasteboard: .general) }

    init(store: ClipboardStore, pasteboard: NSPasteboard, monitor: Bool = true) {
        self.store = store
        self.pasteboard = pasteboard
        // The contents that predate launch were never copied while history was running.
        lastChange = pasteboard.changeCount
        guard monitor else { return }
        observer = DistributedNotificationCenter.default().addObserver(forName: Self.changes, object: nil, queue: .main) { [weak self] note in
            let origin = note.object as? String
            Task { @MainActor in
                guard let self, origin != self.instance else { return }
                await self.synchronize()
            }
        }
        self.monitor = Task { [weak self] in
            await self?.synchronize()
            while !Task.isCancelled {
                guard self != nil else { return }
                await self?.poll()
                try? await Task.sleep(nanoseconds: 300_000_000)
            }
        }
    }

    deinit {
        monitor?.cancel()
        if let observer { DistributedNotificationCenter.default().removeObserver(observer) }
    }

    private func perform<T>(_ operation: @escaping @Sendable (ClipboardStore) throws -> T) async throws -> T {
        let store = self.store
        return try await withCheckedThrowingContinuation { continuation in
            worker.async { continuation.resume(with: Result { try operation(store) }) }
        }
    }

    private var accessIssue: String? {
        if #available(macOS 15.4, *), pasteboard.name == .general {
            switch pasteboard.accessBehavior {
            case .ask, .alwaysDeny:
                return "Choose Always Allow for this app’s clipboard access in System Settings to record new copies."
            default: break
            }
        }
        return nil
    }

    func synchronize() async {
        revision &+= 1
        let requested = revision
        do {
            let (rows, isPaused) = try await perform { store in (try store.entries(), try store.isPaused()) }
            guard requested == revision else { return }
            if isPaused != paused { lastChange = pasteboard.changeCount; paused = isPaused }
            if entries != rows { entries = rows }
            issue = paused ? nil : accessIssue
        } catch { issue = "Clipboard history storage is unavailable. Check your available disk space and reopen the window." }
    }

    func poll(frontmostBundleID: String? = nil) async {
        let count = pasteboard.changeCount
        if count != lastChange {
            lastChange = count
            emptyRetries = 4
        } else if emptyRetries == 0 { return }
        emptyRetries -= 1
        guard !paused else { emptyRetries = 0; return }
        if let accessIssue { emptyRetries = 0; issue = accessIssue; return }
        let name = pasteboard.name.rawValue
        let front = frontmostBundleID ?? (pasteboard.name == .general ? NSWorkspace.shared.frontmostApplication?.bundleIdentifier : nil)
        let now = Date()
        let generation = Self.bootSession + "." + name + "." + String(count)
        do {
            let (changed, empty) = try await perform { store -> (Bool, Bool) in
                guard try !store.isPaused(), !ClipboardPasteboard.ignores(front) else { return (false, false) }
                let board = name == NSPasteboard.Name.general.rawValue ? NSPasteboard.general : NSPasteboard(name: .init(name))
                guard board.changeCount == count else { return (false, false) }
                // Some writers clear, render, then set data without incrementing changeCount again.
                guard board.types?.isEmpty == false else { return (false, true) }
                let contents = ClipboardPasteboard.read(board, expectedChange: count, frontmostBundleID: front)
                guard !contents.isEmpty else { return (false, false) }
                return (try store.record(contents, observing: generation, at: now), false)
            }
            if !empty, lastChange == count { emptyRetries = 0 }
            if changed { await didChange() }
        } catch { issue = "Couldn’t save the copied item to clipboard history." }
    }

    private func didChange() async {
        DistributedNotificationCenter.default().postNotificationName(Self.changes, object: instance, userInfo: nil, deliverImmediately: true)
        await synchronize()
    }

    func entries(matching query: String) async -> [ClipboardEntry] {
        do { return try await perform { try $0.entries(matching: query) } }
        catch { issue = "Couldn’t search clipboard history."; return [] }
    }

    func content(for entry: ClipboardEntry) async -> ClipboardContent? {
        do { return try await perform { try $0.content(for: entry.id) } }
        catch { issue = "Couldn’t read this clipboard entry."; return nil }
    }

    func setPaused(_ value: Bool) {
        paused = value
        lastChange = pasteboard.changeCount
        emptyRetries = 0
        modify { try $0.setPaused(value) }
    }

    func remove(_ entry: ClipboardEntry) { modify { try $0.remove(entry.id) } }

    func clear() { modify { try $0.clear() } }

    private func modify(_ update: @escaping @Sendable (ClipboardStore) throws -> Void) {
        Task {
            do {
                try await perform(update)
                await didChange()
            } catch {
                await synchronize()
                issue = "Couldn’t update clipboard history. Please try again."
            }
        }
    }

    func commands() -> [ToolCommand] {
        [ToolCommand(id: "clipboard.history", title: "Clipboard History", subtitle: "Find and paste copied text and images",
                     symbol: "list.clipboard", group: "Clipboard", keywords: "pasteboard recent copies screenshots photos text") {
            self.showHistory()
        }]
    }

    func showHistory() {
        pasteTarget = TargetApplication.current
        window.toggle()
        Task { await synchronize() }
    }

    func copy(_ entry: ClipboardEntry) { restore(entry, paste: false) }
    func paste(_ entry: ClipboardEntry) { restore(entry, paste: true) }

    private func restore(_ entry: ClipboardEntry, paste: Bool) {
        let target = pasteTarget
        Task {
            guard let content = await content(for: entry) else {
                await synchronize()
                issue = "That entry is no longer available."
                return
            }
            guard ClipboardPasteboard.write(content, to: pasteboard) else { issue = "Couldn’t write to the clipboard."; return }
            lastChange = pasteboard.changeCount
            let savedChange = lastChange
            window.hide()
            guard paste else { Feedback.show("Copied to clipboard"); return }
            guard AXIsProcessTrusted(), CGPreflightPostEventAccess() else {
                Feedback.show("Copied. Press ⌘V to paste. Direct paste requires Accessibility access.")
                return
            }
            guard let target, !target.isTerminated else {
                Feedback.show("Copied. Press ⌘V in the app where you want to paste.")
                return
            }
            let front = NSWorkspace.shared.frontmostApplication
            if front?.processIdentifier == NSRunningApplication.current.processIdentifier {
                target.activate(options: [.activateIgnoringOtherApps])
            }
            // Wait for focus to return after dismissing the window. Deliver events to
            // the original process only, and abandon the paste if another app took focus.
            for _ in 0..<20 {
                let frontPID = NSWorkspace.shared.frontmostApplication?.processIdentifier
                if frontPID == target.processIdentifier { break }
                if let frontPID, frontPID != NSRunningApplication.current.processIdentifier { break }
                try? await Task.sleep(nanoseconds: 20_000_000)
            }
            guard pasteboard.changeCount == savedChange else {
                Feedback.show("The clipboard changed. Select the entry again to paste it.")
                return
            }
            guard NSWorkspace.shared.frontmostApplication?.processIdentifier == target.processIdentifier,
                  Self.postPaste(to: target.processIdentifier) else {
                Feedback.show("Copied. Press ⌘V in the app where you want to paste.")
                return
            }
        }
    }

    private static func postPaste(to pid: pid_t) -> Bool {
        guard let source = CGEventSource(stateID: .privateState) else { return false }
        // Command shortcuts follow the active keyboard layout. Try the ANSI V key first.
        let keys: [CGKeyCode] = [9] + (0..<128).filter { $0 != 9 }
        let down = keys.lazy.compactMap { code -> CGEvent? in
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: code, keyDown: true) else { return nil }
            event.flags = .maskCommand
            return NSEvent(cgEvent: event)?.characters(byApplyingModifiers: .command)?.lowercased() == "v" ? event : nil
        }.first
        guard let down, let up = down.copy() else { return false }
        up.type = .keyUp
        up.flags = .maskCommand
        down.postToPid(pid)
        up.postToPid(pid)
        return true
    }
}
