import AppKit
import ImageIO
import UniformTypeIdentifiers

enum ClipboardMember: Equatable, Sendable {
    case content(ClipboardContent)
    case representation(ClipboardRepresentation)
}

/// Keep the separate representations of each pasteboard item together, in source order.
enum ClipboardPasteboard {
    private static let restored = NSPasteboard.PasteboardType("org.nspasteboard.RestoredType")
    private static let source = NSPasteboard.PasteboardType("org.nspasteboard.source")
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        restored, .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
        .init("de.petermaurer.TransientPasteboardType"), .init("com.typeit4me.clipping"),
        .init("Pasteboard generator type"), .init("com.apple.is-remote-clipboard")
    ]
    private static let privateApps = [
        "com.apple.passwords", "com.apple.keychainaccess", "com.1password.1password",
        "com.agilebits.onepassword", "com.bitwarden.desktop", "com.bitwarden.desktop.mas",
        "com.dashlane.dashlanephonefinal", "org.keepassxc.keepassxc", "in.sinew.enpass-desktop"
    ]

    static func ignores(_ bundleID: String?) -> Bool {
        guard let id = bundleID?.lowercased() else { return false }
        if id.hasPrefix("com.agilebits.onepassword") { return true }
        return privateApps.contains { id == $0 || id.hasPrefix($0 + ".") }
    }

    static func taggedSources(in items: [NSPasteboardItem]) -> [String] {
        items.compactMap { $0.types.contains(source) ? $0.string(forType: source) : nil }
    }

    // Pasteboard ownership, change markers and file promises describe the live
    // pasteboard or request future work. They must not be replayed as user content.
    private static func storable(_ type: NSPasteboard.PasteboardType) -> Bool {
        let name = type.rawValue.lowercased()
        return type != source && !ignoredTypes.contains(type) && !name.contains("promise")
            && !name.hasPrefix("org.nspasteboard.") && !name.hasPrefix("com.apple.pasteboard.")
            && !name.contains("pboardtype") && !name.hasPrefix("dyn.")
    }

    static func capture(_ board: NSPasteboard, expectedChange: Int, frontmostBundleID: String?, frontmostName: String? = nil,
                        privacy: ClipboardPrivacy = .init()) -> ClipboardCapture? {
        guard board.changeCount == expectedChange, !ignores(frontmostBundleID), !privacy.excludes(frontmostBundleID),
              let types = board.types, ignoredTypes.isDisjoint(with: types),
              let items = board.pasteboardItems, !items.isEmpty, items.count <= 200,
              items.allSatisfy({ ignoredTypes.isDisjoint(with: $0.types) }) else { return nil }
        let tagged = taggedSources(in: items)
        guard tagged.allSatisfy({ !ignores($0) && !privacy.excludes($0) }) else { return nil }
        let sourceID = tagged.first { !$0.isEmpty } ?? frontmostBundleID
        var previews: [ClipboardContent] = []
        var originals: [[ClipboardRepresentation]] = []
        let limit = ClipboardStore.maximumItemBytes
        var originalBytes = 0
        var previewBytes = 0
        var fitsOriginals = true
        for item in items {
            guard board.changeCount == expectedChange else { return nil }
            if fitsOriginals {
                var representations: [ClipboardRepresentation] = []
                for type in item.types where storable(type) {
                    guard let data = item.data(forType: type), !data.isEmpty else { continue }
                    originalBytes += data.count
                    if originalBytes > limit {
                        fitsOriginals = false
                        originals.removeAll()
                        break
                    }
                    representations.append(ClipboardRepresentation(type: type.rawValue, data: data))
                }
                if fitsOriginals {
                    guard !representations.isEmpty else { return nil }
                    originals.append(representations)
                }
            }
            if let content = preview(item) {
                switch content {
                case .text(let text): previewBytes += text.utf8.count
                case .image(let bytes): previewBytes += bytes.count
                case .files(let urls): previewBytes += urls.reduce(0) { $0 + $1.path.utf8.count }
                }
                guard previewBytes <= limit else { return nil }
                previews.append(content)
            }
        }
        guard board.changeCount == expectedChange, let first = previews.first else { return nil }
        let content: ClipboardContent
        let files = previews.flatMap { if case .files(let urls) = $0 { return urls }; return [] }
        let texts = previews.compactMap { if case .text(let text) = $0 { return text }; return nil }
        if files.count == items.count { content = .files(files) }
        else if texts.count == items.count { content = .text(texts.joined(separator: "\n")) }
        else { content = first }
        // Keep a valid canonical-only single entry if its source representations
        // exceed the per-entry storage cap, e.g. an uncompressed TIFF plus a PNG.
        // Multi-item copies always round-trip as a complete group.
        let canonical: Data?
        switch content {
        case .text(let text): canonical = Data(text.utf8)
        case .image(let bytes): canonical = bytes
        case .files(let urls): canonical = try? PropertyListEncoder().encode(urls.map(\.path))
        }
        guard let canonical, canonical.count <= limit else { return nil }
        let extras = originals.joined().reduce(0) { $0 + ($1.data == canonical ? 0 : $1.data.count) }
        if !fitsOriginals || extras > limit - canonical.count {
            if items.count > 1, files.count != items.count { return nil }
            originals.removeAll()
        }
        let sourceName: String?
        if let id = sourceID, id == frontmostBundleID, let frontmostName { sourceName = frontmostName }
        else if let id = sourceID, let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: id) {
            sourceName = FileManager.default.displayName(atPath: url.path).replacingOccurrences(of: "\\.app$", with: "", options: .regularExpression)
        } else { sourceName = nil }
        return ClipboardCapture(content: content, items: originals, sourceBundleID: sourceID, sourceName: sourceName,
                                observedBundleIDs: tagged + [frontmostBundleID].compactMap { $0 })
    }

    static func read(_ board: NSPasteboard, expectedChange: Int, frontmostBundleID: String?) -> [ClipboardContent] {
        capture(board, expectedChange: expectedChange, frontmostBundleID: frontmostBundleID).map { [$0.content] } ?? []
    }

    /// Decode the saved archive locally. A group's primary preview may describe just
    /// its first item. File, sharing, and inspector actions need each ordered member.
    static func members(of capture: ClipboardCapture) -> [ClipboardMember] {
        if capture.items.count <= 1 {
            if case .files(let urls) = capture.content { return urls.map { .content(.files([$0])) } }
            return [.content(capture.content)]
        }
        var members: [ClipboardMember] = []
        for representations in capture.items {
            guard let first = representations.first else { return [] }
            let item = NSPasteboardItem()
            for rep in representations { item.setData(rep.data, forType: .init(rep.type)) }
            let member = preview(item).map(ClipboardMember.content) ?? .representation(first)
            members.append(member)
        }
        return members
    }

    private static func preview(_ item: NSPasteboardItem) -> ClipboardContent? {
        if let path = item.string(forType: .fileURL), let url = URL(string: path), url.isFileURL {
            return .files([url])
        }
        if let data = boundedData(item, type: .color),
           let color = (try? NSKeyedUnarchiver.unarchivedObject(ofClass: NSColor.self, from: data))?.usingColorSpace(.sRGB) {
            let components = [color.redComponent, color.greenComponent, color.blueComponent, color.alphaComponent]
            guard components.allSatisfy(\.isFinite) else { return nil }
            let channels = components.map { UInt8((min(1, max(0, $0)) * 255).rounded()) }
            let hex = channels.prefix(channels[3] == 255 ? 3 : 4).map { String(format: "%02X", $0) }.joined()
            return .text("#" + hex)
        }
        let imageTypes = [.png, .tiff] + item.types.filter {
            $0 != .png && $0 != .tiff && UTType($0.rawValue)?.conforms(to: .image) == true
        }
        for type in imageTypes where item.types.contains(type) {
            if let data = item.data(forType: type), let image = normalizedImage(data) { return .image(image) }
        }
        let text = item.string(forType: .string) ?? item.string(forType: .URL)
        if let text, !text.isEmpty, text.utf8.count <= ClipboardStore.maximumItemBytes { return .text(text) }
        if let data = boundedData(item, type: .rtf), let s = NSAttributedString(rtf: data, documentAttributes: nil)?.string, !s.isEmpty { return .text(s) }
        if let data = boundedData(item, type: .rtfd), let s = NSAttributedString(rtfd: data, documentAttributes: nil)?.string, !s.isEmpty { return .text(s) }
        if let data = boundedData(item, type: .html), let doc = try? XMLDocument(data: data, options: [.documentTidyHTML, .nodeLoadExternalEntitiesNever]) {
            let nodes = (try? doc.nodes(forXPath: "//body//text()[not(ancestor::script) and not(ancestor::style)]")) ?? []
            let text = nodes.compactMap(\.stringValue).joined(separator: " ").trimmingCharacters(in: .whitespacesAndNewlines)
            if !text.isEmpty { return .text(text) }
        }
        return nil
    }

    /// Pasteboard data can be supplied lazily. Check its size before asking a
    /// document parser to expand it, including the canonical-preview fallback.
    private static func boundedData(_ item: NSPasteboardItem, type: NSPasteboard.PasteboardType) -> Data? {
        guard let bytes = item.data(forType: type), !bytes.isEmpty, bytes.count <= ClipboardStore.maximumItemBytes else { return nil }
        return bytes
    }

    private static func normalizedImage(_ data: Data) -> Data? {
        guard data.count <= 128 * 1024 * 1024,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [String: Any],
              let width = properties[kCGImagePropertyPixelWidth as String] as? Int,
              let height = properties[kCGImagePropertyPixelHeight as String] as? Int,
              width > 0, height > 0, width <= 48_000_000 / height else { return nil }
        if CGImageSourceGetType(source) as String? == UTType.png.identifier {
            return data.count <= ClipboardStore.maximumItemBytes ? data : nil
        }
        let png = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(png, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImageFromSource(dest, source, 0, nil)
        guard CGImageDestinationFinalize(dest), png.length <= ClipboardStore.maximumItemBytes else { return nil }
        return png as Data
    }

    static func formatName(_ type: String) -> String {
        switch NSPasteboard.PasteboardType(type) {
        case .string: return "Plain Text"
        case .rtf: return "Rich Text (RTF)"
        case .rtfd: return "Rich Text with Attachments"
        case .html: return "HTML"
        case .png: return "PNG"
        case .tiff: return "TIFF"
        case .fileURL: return "File URL"
        case .color: return "Color"
        case .URL: return "URL"
        default: return UTType(type)?.localizedDescription ?? type
        }
    }

    static func formats(_ capture: ClipboardCapture) -> [String] {
        // A narrower representation must preserve every item. Only offer original
        // types common to the entire group, plus an explicitly convertible preview.
        let first = capture.items.first ?? []
        var result = first.map(\.type).filter { type in capture.items.allSatisfy { $0.contains { $0.type == type } } }
        let canonical: String
        switch capture.content {
        case .text: canonical = NSPasteboard.PasteboardType.string.rawValue
        case .image: canonical = NSPasteboard.PasteboardType.png.rawValue
        case .files: canonical = NSPasteboard.PasteboardType.fileURL.rawValue
        }
        if !result.contains(canonical), capture.items.count <= 1 { result.append(canonical) }
        return result
    }

    static func write(_ capture: ClipboardCapture, as type: String? = nil, to board: NSPasteboard) -> Bool {
        if !capture.items.isEmpty {
            var items: [NSPasteboardItem] = []
            for representations in capture.items {
                let item = NSPasteboardItem()
                let matching = representations.filter { (type == nil || $0.type == type) && storable(.init($0.type)) }
                if matching.isEmpty {
                    guard let type, capture.items.count == 1, formats(capture).contains(type) else { return false }
                    return write(capture.content, to: board)
                }
                for rep in matching {
                    guard item.setData(rep.data, forType: .init(rep.type)) else { return false }
                }
                items.append(item)
            }
            return writeItems(items, to: board)
        }
        if let type, !formats(capture).contains(type) { return false }
        return write(capture.content, to: board)
    }

    static func write(_ content: ClipboardContent, to board: NSPasteboard) -> Bool {
        var items: [NSPasteboardItem] = []
        let one = NSPasteboardItem()
        switch content {
        case .text(let text):
            guard one.setString(text, forType: .string) else { return false }
            items = [one]
        case .image(let png):
            guard one.setData(png, forType: .png) else { return false }
            items = [one]
        case .files(let urls):
            for url in urls {
                let item = NSPasteboardItem()
                guard item.setString(url.absoluteString, forType: .fileURL) else { return false }
                items.append(item)
            }
        }
        return writeItems(items, to: board)
    }

    private static func writeItems(_ items: [NSPasteboardItem], to board: NSPasteboard) -> Bool {
        guard !items.isEmpty else { return false }
        for item in items {
            item.setData(Data(), forType: restored)
            item.setString("", forType: source)
        }
        board.clearContents()
        return board.writeObjects(items)
    }
}
