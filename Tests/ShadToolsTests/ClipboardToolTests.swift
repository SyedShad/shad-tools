import AppKit
import ImageIO
import Testing
import UniformTypeIdentifiers
@testable import ShadTools

@Suite("Clipboard monitoring")
struct ClipboardToolTests {
    @Test @MainActor func observesOnlyNewCopiesAndAvoidsRecapturingItsOwnWrites() async throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: directory) }
        let store = ClipboardStore(directory: directory)
        board.setString("predates launch", forType: .string)
        let tool = ClipboardTool(store: store, pasteboard: board, monitor: false)
        await tool.poll()
        #expect(try store.entries().isEmpty)
        board.clearContents()
        board.setString("one", forType: .string)
        await tool.poll()
        board.clearContents()
        board.setString("two", forType: .string)
        await tool.poll()
        board.clearContents()
        board.setString("one", forType: .string)
        await tool.poll()
        #expect(tool.entries.map(\.title) == ["one", "two"])
        let before = tool.entries
        #expect(ClipboardPasteboard.write(.text("two"), to: board))
        #expect(board.string(forType: .string) == "two")
        await tool.poll()
        #expect(try store.entries() == before)
        try store.setPaused(true)
        board.clearContents()
        board.setString("while paused", forType: .string)
        await tool.poll()
        #expect(try store.entries() == before)
    }

    @Test @MainActor func handlesDelayedWritersAndTwoRunningEditionsAcrossDeletion() async throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: directory) }
        let store = ClipboardStore(directory: directory)
        let first = ClipboardTool(store: store, pasteboard: board, monitor: false)
        let second = ClipboardTool(store: ClipboardStore(directory: directory), pasteboard: board, monitor: false)
        let generation = board.clearContents()
        await first.poll()
        board.setString("fixture", forType: .string)
        #expect(board.changeCount == generation)
        await first.poll()
        let entry = try #require(try store.entries().first)
        try store.remove(entry.id)
        await second.poll()
        #expect(try store.entries().isEmpty)
        board.clearContents()
        board.setString("fixture", forType: .string)
        await second.poll()
        #expect(try store.entries().map(\.id) == [entry.id])
    }

    @Test func respectsSensitiveAndTransientTypesAcrossItemsAndSourceApps() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let types = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                     "org.nspasteboard.AutoGeneratedType", "com.apple.is-remote-clipboard", "com.agilebits.onepassword"]
        for raw in types {
            let text = NSPasteboardItem()
            text.setString("private fixture", forType: .string)
            let marker = NSPasteboardItem()
            marker.setData(Data(), forType: .init(raw))
            board.clearContents()
            #expect(board.writeObjects([text, marker]))
            #expect(ClipboardPasteboard.read(board, expectedChange: board.changeCount, frontmostBundleID: nil).isEmpty)
        }
        let source = NSPasteboardItem()
        source.setString("ignored", forType: .string)
        source.setString("com.1password.1password", forType: .init("org.nspasteboard.source"))
        board.clearContents()
        #expect(board.writeObjects([source]))
        #expect(ClipboardPasteboard.read(board, expectedChange: board.changeCount, frontmostBundleID: nil).isEmpty)
        board.clearContents()
        board.setString("fixture", forType: .string)
        #expect(ClipboardPasteboard.read(board, expectedChange: board.changeCount, frontmostBundleID: "com.apple.Passwords").isEmpty)
        #expect(ClipboardPasteboard.read(board, expectedChange: board.changeCount - 1, frontmostBundleID: nil).isEmpty)
    }

    @Test func normalizesCopiedImagesAndRestoresTheirPixels() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let bitmap = try #require(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 4, pixelsHigh: 3, bitsPerSample: 8,
                                                     samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
                                                     colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
        let pixels = try #require(bitmap.bitmapData)
        for y in 0..<bitmap.pixelsHigh {
            for x in 0..<bitmap.pixelsWide {
                let offset = y * bitmap.bytesPerRow + x * 4
                pixels[offset] = 255
                pixels[offset + 1] = 0
                pixels[offset + 2] = 0
                pixels[offset + 3] = 255
            }
        }
        for format: (NSBitmapImageRep.FileType, NSPasteboard.PasteboardType) in [(.tiff, .tiff), (.png, .png)] {
            let original = try #require(bitmap.representation(using: format.0, properties: [:]))
            let item = NSPasteboardItem()
            item.setData(original, forType: format.1)
            item.setString("image description", forType: .string)
            board.clearContents()
            #expect(board.writeObjects([item]))
            let captured = try #require(ClipboardPasteboard.read(board, expectedChange: board.changeCount, frontmostBundleID: nil).first)
            guard case .image(let data) = captured else { Issue.record("Expected image to win over alt text"); return }
            let source = try #require(CGImageSourceCreateWithData(data as CFData, nil))
            #expect(CGImageSourceGetType(source) as String? == UTType.png.identifier)
            #expect(ClipboardPasteboard.write(captured, to: board))
            #expect(NSImage(pasteboard: board) != nil)
            #expect(board.data(forType: .tiff) != nil)
            let restored = try #require(board.data(forType: .png).flatMap(NSBitmapImageRep.init(data:)))
            #expect(restored.pixelsWide == 4 && restored.pixelsHigh == 3)
            let originalBitmap = try #require(NSBitmapImageRep(data: original))
            let expected = try #require(originalBitmap.colorAt(x: 2, y: 1)?.usingColorSpace(.sRGB))
            let pixel = try #require(restored.colorAt(x: 2, y: 1)?.usingColorSpace(.sRGB))
            #expect(expected.redComponent > 0.9 && expected.alphaComponent == 1)
            #expect(abs(pixel.redComponent - expected.redComponent) < 0.01)
            #expect(abs(pixel.greenComponent - expected.greenComponent) < 0.01)
            #expect(abs(pixel.blueComponent - expected.blueComponent) < 0.01)
            #expect(abs(pixel.alphaComponent - expected.alphaComponent) < 0.01)
        }
    }
}
